describe('prefer-unique-id (route templates render once)', () => {
  const ids = (src, filename) => lintTemplate(src, { filename, minSeverity: 'info' }).filter((f) => f.ruleId === 'prefer-unique-id').length;
  const SRC = '<label for="n">Name</label><input id="n">';
  test.each([
    ['app/templates/settings.hbs', 0],
    ['app/templates/settings.gjs', 0],
    ['app/templates/components/x.hbs', 1],
    ['app/components/x.hbs', 1],
    ['app/components/templates/x.hbs', 1],
    [undefined, 1],
  ])('%s', (filename, n) => {
    expect(ids(filename?.endsWith('.gjs') ? `<template>${SRC}</template>` : SRC, filename)).toBe(n);
  });

  test('ids inside {{#each}} still repeat in a route template', () => {
    expect(ids('{{#each @rows as |r|}}<label for="n">{{r}}</label><input id="n">{{/each}}', 'app/templates/x.hbs')).toBe(1);
  });
});

describe('help text', () => {
  const find = (src, rule) => lintTemplate(src, { filename: 't.hbs', minSeverity: 'info' }).find((f) => f.ruleId === rule);
  test.each([
    ['<div role="slider" aria-label="v"></div>', 'aria-valuenow', 'aria-valuenow={{this.value}}'],
    ['<div role="heading">x</div>', 'aria-level', 'aria-level="2"'],
    ['<div role="checkbox" aria-label="x"></div>', 'aria-checked', 'aria-checked={{this.checked}}'],
    ['<div role="combobox" aria-label="x" aria-controls="p"></div><div id="p"></div>', 'aria-expanded', 'aria-expanded={{if this.expanded "true" "false"}}'],
  ])('required-attribute example for %s fits the value type', (src, attr, example) => {
    const f = lintTemplate(src, { filename: 't.hbs', minSeverity: 'info' }).find((x) => x.ruleId === 'aria-required-attributes' && x.message.includes(attr));
    expect(f.help).toContain(`e.g. ${example}.`);
    expect(f.help).not.toContain('isOn');
  });

  test('img with ...attributes suggests alt="" before ...attributes', () => {
    expect(find('<img src="x.png" ...attributes>', 'accessible-name').help).toContain('<img alt="" ...attributes>');
    expect(find('<img src="x.png">', 'accessible-name').help).not.toContain('...attributes');
  });

  test('no-autofocus cites 2.4.3 only', () => {
    expect(find('<input autofocus aria-label="x">', 'no-autofocus').wcag).toEqual(['WCAG 2.4.3 Focus Order (A)']);
  });
});

